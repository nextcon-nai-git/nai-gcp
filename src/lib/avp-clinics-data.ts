export function getClinicById(id: string): GlobalClinic | undefined {
  return GLOBAL_CLINICS_CATALOG.find((c) => c.id === id);
}

export function getClinicsByUF(uf: string): GlobalClinic[] {
  return GLOBAL_CLINICS_CATALOG.filter((c) => c.ufs.includes(uf.toUpperCase()));
}

export function getClinicsByCity(city: string): GlobalClinic[] {
  const norm = city.toLowerCase();
  return GLOBAL_CLINICS_CATALOG.filter((c) =>
    c.cities.some((ci) => ci.toLowerCase().includes(norm))
  );
}

export function searchClinics(query: string, ufFilter?: string): GlobalClinic[] {
  const q = query.trim().toLowerCase();
  return GLOBAL_CLINICS_CATALOG.filter((c) => {
    const matchesQ =
      !q ||
      c.name.toLowerCase().includes(q) ||
      c.cities.some((ci) => ci.toLowerCase().includes(q)) ||
      c.sampleAddress.toLowerCase().includes(q);
    const matchesUF = !ufFilter || ufFilter === "ALL" || c.ufs.includes(ufFilter.toUpperCase());
    return matchesQ && matchesUF;
  });
}
