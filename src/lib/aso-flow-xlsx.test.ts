// @vitest-environment node
import { crc32, deflateRawSync } from "node:zlib";
import JSZip from "jszip";
import { Workbook } from "exceljs";
import { afterEach, describe, expect, it, vi } from "vitest";
import { readAsoFlowFile } from "./aso-flow-import";
import { ASO_XLSX_ENTRY_LIMIT, ASO_XLSX_EXPANDED_LIMIT, assertSafeAsoXlsx } from "./aso-flow-xlsx";

async function archive(content = "<worksheet/>", streamFiles = false): Promise<ArrayBuffer> {
  const zip = new JSZip();
  zip.file("xl/worksheets/sheet1.xml", content, { createFolders: false });
  return zip.generateAsync({
    type: "arraybuffer",
    compression: "DEFLATE",
    streamFiles,
  });
}

function directory(bytes: ArrayBuffer) {
  const view = new DataView(bytes);
  const end = bytes.byteLength - 22;
  return { view, end, start: view.getUint32(end + 16, true) };
}

async function nativeDeflateArchive(content: Uint8Array): Promise<ArrayBuffer> {
  // Keep ZIP32 framing generated by JSZip, but compress the large fixture in
  // native code so coverage does not spend the test budget on its compressor.
  // The production streaming decompression remains completely real.
  const template = await archive();
  const { view, start, end } = directory(template);
  const dataStart = 30 + view.getUint16(26, true) + view.getUint16(28, true);
  const local = Buffer.from(template.slice(0, dataStart));
  const central = Buffer.from(template.slice(start, end));
  const footer = Buffer.from(template.slice(end));
  const compressed = deflateRawSync(content);
  const checksum = crc32(content);
  local.writeUInt32LE(checksum, 14);
  local.writeUInt32LE(compressed.byteLength, 18);
  local.writeUInt32LE(content.byteLength, 22);
  central.writeUInt32LE(checksum, 16);
  central.writeUInt32LE(compressed.byteLength, 20);
  central.writeUInt32LE(content.byteLength, 24);
  footer.writeUInt32LE(local.byteLength + compressed.byteLength, 16);
  return Uint8Array.from(Buffer.concat([local, compressed, central, footer])).buffer;
}

afterEach(() => vi.restoreAllMocks());

describe("limites de descompactação da importação ASO", () => {
  it.each([false, true])(
    "aceita arquivos ZIP comuns e dados com descritor (%s)",
    async (streamFiles) => {
      await expect(
        assertSafeAsoXlsx(await archive("<worksheet/>", streamFiles))
      ).resolves.toBeUndefined();
    }
  );

  it("recusa o tamanho expandido declarado antes de carregar entradas no JSZip", async () => {
    const bytes = await archive();
    const { view, start } = directory(bytes);
    view.setUint32(start + 24, ASO_XLSX_EXPANDED_LIMIT + 1, true);
    const load = vi.spyOn(JSZip, "loadAsync");
    await expect(assertSafeAsoXlsx(bytes)).rejects.toThrow("32 MB após descompactação");
    expect(load).not.toHaveBeenCalled();
  });

  it("interrompe a saída real mesmo quando o ZIP declara um tamanho falso pequeno", async () => {
    const bytes = await nativeDeflateArchive(new Uint8Array(ASO_XLSX_EXPANDED_LIMIT + 1).fill(120));
    const { view, start } = directory(bytes);
    view.setUint32(start + 24, 1, true);
    view.setUint32(22, 1, true);
    expect(bytes.byteLength).toBeLessThan(100_000);
    await expect(assertSafeAsoXlsx(bytes)).rejects.toThrow("32 MB após descompactação");
  });

  it("conta entradas reais mesmo com quantidade declarada falsa", async () => {
    const zip = new JSZip();
    for (let index = 0; index <= ASO_XLSX_ENTRY_LIMIT; index++) zip.file(`entry-${index}`, "");
    const bytes = await zip.generateAsync({ type: "arraybuffer" });
    const { view, end } = directory(bytes);
    view.setUint16(end + 8, 1, true);
    view.setUint16(end + 10, 1, true);
    const load = vi.spyOn(JSZip, "loadAsync");
    await expect(assertSafeAsoXlsx(bytes)).rejects.toThrow("componentes demais");
    expect(load).not.toHaveBeenCalled();
  });

  it("não valida um diretório enquanto o JSZip escolheria outro dentro do comentário", async () => {
    const outer = await archive();
    const nested = new JSZip();
    for (let index = 0; index <= ASO_XLSX_ENTRY_LIMIT; index++) nested.file(`e${index}`, "");
    const inner = await nested.generateAsync({ type: "uint8array" });
    expect(inner.byteLength + 1).toBeLessThan(65536);
    const bytes = new Uint8Array(outer.byteLength + inner.byteLength + 1);
    bytes.set(new Uint8Array(outer));
    bytes.set(inner, outer.byteLength);
    new DataView(bytes.buffer).setUint16(outer.byteLength - 2, inner.byteLength + 1, true);
    // The outer directory has one entry and a valid comment length. JSZip's
    // last-signature rule would otherwise choose the nested archive, despite
    // its undeclared trailing byte, and allocate all its entries before limits.
    expect(Object.keys((await JSZip.loadAsync(bytes.buffer)).files)).toHaveLength(
      ASO_XLSX_ENTRY_LIMIT + 1
    );
    const load = vi.spyOn(JSZip, "loadAsync");
    await expect(assertSafeAsoXlsx(bytes.buffer)).rejects.toThrow("XLSX inválido");
    expect(load).not.toHaveBeenCalled();
  });

  it("preserva comentários ZIP comuns", async () => {
    const zip = new JSZip();
    zip.file("xl/worksheets/sheet1.xml", "<worksheet/>", { createFolders: false });
    const bytes = await zip.generateAsync({ type: "arraybuffer", comment: "Dados conferidos" });
    await expect(assertSafeAsoXlsx(bytes)).resolves.toBeUndefined();
  });

  it.each(["encryption", "zip64", "local-offset", "directory-count", "truncation"])(
    "recusa estrutura não suportada ou adulterada: %s",
    async (change) => {
      let bytes = await archive();
      const { view, start, end } = directory(bytes);
      if (change === "encryption") view.setUint16(start + 8, 1, true);
      if (change === "zip64") view.setUint32(end + 12, 0xffffffff, true);
      if (change === "local-offset") view.setUint32(start + 42, bytes.byteLength, true);
      if (change === "directory-count") {
        view.setUint16(end + 8, 2, true);
        view.setUint16(end + 10, 2, true);
      }
      if (change === "truncation") bytes = bytes.slice(0, -1);
      await expect(assertSafeAsoXlsx(bytes)).rejects.toThrow("XLSX inválido ou não suportado");
    }
  );

  it("recusa um arquivo pequeno que não é um contêiner XLSX", async () => {
    await expect(assertSafeAsoXlsx(new ArrayBuffer(3))).rejects.toThrow("XLSX inválido");
  });

  it("ainda importa um XLSX real e preserva CPF textual", async () => {
    const workbook = new Workbook();
    const sheet = workbook.addWorksheet("Dados");
    sheet.addRow([
      "CNPJ empregador",
      "CPF",
      "Colaborador",
      "Cidade",
      "UF",
      "Unidade",
      "Tipo de exame",
      "Competência",
      "Cargo",
      "Setor",
    ]);
    sheet.addRow([
      "00.000.000/0001-00",
      "000.000.000-00",
      "Pessoa de teste",
      "Curitiba",
      "pr",
      "Unidade",
      "Periódico",
      "11/2026",
      "Cargo",
      "Setor",
    ]);
    const bytes = await workbook.xlsx.writeBuffer();
    const file = new File([new Uint8Array(bytes as unknown as ArrayBuffer)], "dados.xlsx");
    await expect(readAsoFlowFile(file)).resolves.toEqual([
      {
        companyCnpj: "00.000.000/0001-00",
        employeeCpf: "000.000.000-00",
        employeeName: "Pessoa de teste",
        city: "Curitiba",
        state: "PR",
        unit: "Unidade",
        examType: "periodico",
        cycle: "2026-11",
        roleTitle: "Cargo",
        department: "Setor",
        sourceRow: 2,
      },
    ]);
  });

  it("readAsoFlowFile aplica o limite antes de o ExcelJS interpretar a planilha", async () => {
    const bytes = await archive();
    const { view, start } = directory(bytes);
    view.setUint32(start + 24, ASO_XLSX_EXPANDED_LIMIT + 1, true);
    await expect(readAsoFlowFile(new File([bytes], "dados.xlsx"))).rejects.toThrow(
      "32 MB após descompactação"
    );
  });
});
